-- 05 — Schema `tse_sim`: o que a API do TS Explorer tem e o mock da 012 não
-- tinha (a 012 levantou as 36 tabelas replicadas e registrou que reserva,
-- calendário, check-in e hospedagem NÃO existem no espelho).
--
-- FORA do `public` de propósito: o `public` é a superfície que a 018 vai
-- replicar do espelho real, e nada que nasceu aqui pode se disfarçar de tabela
-- do TSE lá. Quem lê por SQL (erp_ro) continua sem enxergar nada disto.
-- Idempotente: CREATE ... IF NOT EXISTS.

CREATE SCHEMA IF NOT EXISTS tse_sim AUTHORIZATION tse_sim;

-- 038: o que a API de reserva precisa e o mock da 012 não tinha. `unidadehoteleira`
-- só guarda `capacidade`, e não existe tarifa de pontos em lugar nenhum — sem
-- estas duas o `SimularUtilizacaoContrato` não teria o que responder.
CREATE TABLE IF NOT EXISTS tse_sim.tipounidadehoteleira (
  idtipounidadehoteleira  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome                    varchar(40) NOT NULL, -- STANDARD | SUPERIOR | LUXO
  capacidade              integer NOT NULL UNIQUE
);

-- Tarifa em PONTOS por diária + taxa de manutenção, por tipo de UH e período.
-- Dois períodos (PADRÃO e ALTA) porque é o que dá sentido a `DescricaoPeriodo` e
-- `Bloqueado` na simulação — o TSE devolve a tarifa diária a diária.
CREATE TABLE IF NOT EXISTS tse_sim.tarifapontos (
  idtarifapontos          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idtipounidadehoteleira  integer NOT NULL
    REFERENCES tse_sim.tipounidadehoteleira (idtipounidadehoteleira),
  periodo                 varchar(20) NOT NULL, -- PADRÃO | ALTA
  -- meses do período, como lista: alta temporada não é um intervalo contínuo
  -- (jan, fev, jul, dez) e um par início/fim teria que dar a volta no ano
  meses                   integer[] NOT NULL,
  pontospordiaria         integer NOT NULL,
  taxacentavos            bigint NOT NULL,
  -- período fechado para uso: é o que faz o agente dizer "essa semana está
  -- bloqueada" com dado do ERP, em vez de inventar alternativa
  bloqueado               boolean NOT NULL DEFAULT false,
  UNIQUE (idtipounidadehoteleira, periodo)
);

-- utilização de contrato = a reserva (038)
CREATE TABLE IF NOT EXISTS tse_sim.utilizacaocontrato (
  idutilizacao            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idcontrato              integer NOT NULL REFERENCES public.contrato (idcontrato),
  idedificiohotel         integer REFERENCES public.edificiohotel (idedificiohotel),
  idtipounidadehoteleira  integer,
  datacheckin             date NOT NULL,
  datacheckout            date NOT NULL,
  qtdpagantes             integer NOT NULL,
  qtdadultos              integer NOT NULL DEFAULT 0,
  qtdcriancas             integer NOT NULL DEFAULT 0,
  qtdpontosdebitados      integer NOT NULL DEFAULT 0,
  -- taxa de manutenção da utilização, em centavos (o TSE devolve decimal)
  taxacentavos            bigint NOT NULL DEFAULT 0,
  -- quem criou: o TSE distingue robô de humano em IdOperadorRespSolicitacao.
  -- A FK é adicionada no bloco do fim do arquivo, e não aqui: `operador` é
  -- declarada mais abaixo, e num banco NOVO esta referência quebraria o CREATE
  -- (num banco que já tinha a tabela o IF NOT EXISTS escondia o problema).
  idoperador              integer,
  -- PENDENTE | CONFIRMADA | CANCELADA, como o TSE devolve em StatusUtilizacao
  status                  varchar(20) NOT NULL DEFAULT 'PENDENTE',
  datacriacao             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tse_sim.hospede (
  idhospede       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idutilizacao    integer NOT NULL REFERENCES tse_sim.utilizacaocontrato (idutilizacao),
  nome            varchar(120) NOT NULL,
  sobrenome       varchar(120),
  cpf             varchar(14),
  datanascimento  date,
  idfaixaetaria   integer,
  sexo            varchar(20),
  principal       boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS tse_sim.tipopensao (
  idtipopensao   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           varchar(60) NOT NULL, -- CAFE DA MANHA | MEIA PENSAO | PENSAO COMPLETA
  valorcentavos  bigint NOT NULL DEFAULT 0
);

-- "casal" é o lead no vocabulário do TS Explorer (recepcaots/setcasal — 039)
CREATE TABLE IF NOT EXISTS tse_sim.casal (
  idcasal          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome             varchar(120) NOT NULL,
  cpf              varchar(14),
  telefone         varchar(30),
  email            varchar(120),
  idorigemvenda    integer,
  dataagendamento  timestamptz,
  status           varchar(20) NOT NULL DEFAULT 'AGENDADO',
  datacadastro     timestamptz NOT NULL DEFAULT now()
);

-- a baixa de pagamento (036): o POST que faz a parcela virar `pago` no v_titulo
CREATE TABLE IF NOT EXISTS tse_sim.transacaoeletronica (
  idtransacaoeletronica         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idcontafinanceira             integer NOT NULL
    REFERENCES public.contafinanceira (idcontafinanceira),
  valor                         numeric(14, 2) NOT NULL,
  quatroprimeirosdigitoscartao  varchar(4),
  quatroultimosdigitoscartao    varchar(4),
  codigoautorizacao             varchar(40),
  quantidadeparcelas            integer NOT NULL DEFAULT 1,
  nomepessoa                    varchar(120),
  datatransacao                 timestamptz NOT NULL DEFAULT now()
);

-- quem escreve, do lado do TSE: o dono do token (ver TSE_SIM_PAINEL_ESCOPO)
CREATE TABLE IF NOT EXISTS tse_sim.operador (
  idoperador  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login       varchar(60) NOT NULL UNIQUE,
  nome        varchar(120) NOT NULL,
  idpessoa    integer REFERENCES public.pessoa (idpessoa)
);

-- 038: as tabelas acima nasceram na 035 com `IF NOT EXISTS`, então num banco que
-- já rodou aquele seed o CREATE é no-op e as colunas novas NUNCA chegariam.
-- `ADD COLUMN IF NOT EXISTS` é o que faz banco novo e banco antigo convergirem.
ALTER TABLE tse_sim.utilizacaocontrato
  ADD COLUMN IF NOT EXISTS qtdadultos   integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS qtdcriancas  integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS taxacentavos bigint  NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS idoperador   integer;

ALTER TABLE tse_sim.hospede
  ADD COLUMN IF NOT EXISTS sobrenome varchar(120),
  ADD COLUMN IF NOT EXISTS sexo      varchar(20);

-- As FKs de `utilizacaocontrato` são adicionadas AQUI, e não na coluna: um banco
-- que já rodou a 035 tem a tabela criada sem elas, e o `CREATE TABLE IF NOT
-- EXISTS` não voltaria para acrescentá-las. Um mecanismo só, dois bancos iguais.
DO $$
BEGIN
  -- limpa o nome automático que a versão intermediária desta spec deixou
  ALTER TABLE tse_sim.utilizacaocontrato
    DROP CONSTRAINT IF EXISTS utilizacaocontrato_idtipounidadehoteleira_fkey;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'utilizacaocontrato_idoperador_fkey') THEN
    ALTER TABLE tse_sim.utilizacaocontrato
      ADD CONSTRAINT utilizacaocontrato_idoperador_fkey
      FOREIGN KEY (idoperador) REFERENCES tse_sim.operador (idoperador);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'utilizacaocontrato_idtipouh_fkey') THEN
    ALTER TABLE tse_sim.utilizacaocontrato
      ADD CONSTRAINT utilizacaocontrato_idtipouh_fkey
      FOREIGN KEY (idtipounidadehoteleira)
      REFERENCES tse_sim.tipounidadehoteleira (idtipounidadehoteleira);
  END IF;
END $$;

GRANT USAGE ON SCHEMA tse_sim TO tse_sim;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA tse_sim TO tse_sim;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA tse_sim TO tse_sim;
