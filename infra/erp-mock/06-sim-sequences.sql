-- 06 — PKs do 01 viram IDENTITY. Sem isto nenhum INSERT da API do TSE funciona:
-- as tabelas do mock nasceram `integer PRIMARY KEY` puro (o seed sempre soube o
-- id que ia gravar) e o simulador precisa que o banco atribua o próximo.
--
-- `BY DEFAULT` (e não `ALWAYS`) é a escolha que mantém o seed da 012 vivo: ele
-- continua inserindo id explícito e o simulador insere sem id. O preço é que,
-- depois de um seed, as sequências ficam atrás dos ids gravados à mão — daí a
-- função de ressincronização, chamada aqui e de novo por `seedData` no fim da
-- transação de carga (sem ela o segundo `pnpm db:seed` quebra por violação de PK).
--
-- Idempotente: só altera coluna que ainda não é identity.

-- PKs de coluna única e inteira do schema público (tabelapreco tem PK composta
-- e fica de fora — ninguém insere preço de tabela pela API).
CREATE OR REPLACE VIEW tse_sim.pk_identity AS
SELECT c.relname AS tabela, a.attname AS coluna, a.attidentity AS identidade
FROM pg_index i
JOIN pg_class c ON c.oid = i.indrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = i.indkey[0]
WHERE i.indisprimary
  AND i.indnatts = 1
  AND n.nspname = 'public'
  AND c.relkind = 'r'
  AND a.atttypid IN ('integer'::regtype, 'bigint'::regtype);

CREATE OR REPLACE FUNCTION tse_sim.ressincronizar_sequences() RETURNS void AS $$
DECLARE
  r record;
BEGIN
  FOR r IN SELECT * FROM tse_sim.pk_identity LOOP
    -- próxima chave = maior id gravado + 1 (tabela vazia ⇒ 1)
    EXECUTE format(
      'SELECT setval(pg_get_serial_sequence(%L, %L), coalesce(max(%I), 0) + 1, false) FROM public.%I',
      'public.' || r.tabela, r.coluna, r.coluna, r.tabela
    );
  END LOOP;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
  r record;
BEGIN
  FOR r IN SELECT * FROM tse_sim.pk_identity WHERE identidade = '' LOOP
    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',
      r.tabela, r.coluna
    );
  END LOOP;
  PERFORM tse_sim.ressincronizar_sequences();
END $$;

-- o simulador insere: precisa da sequência, não só da tabela
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO tse_sim;
